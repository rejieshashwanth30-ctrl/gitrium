export function generateMockHeatmapData() {
  const data = [];
  const today = new Date("2026-10-28");
  for (let i = 364; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dayOfWeek = d.getDay();
    let count = 0;
    const rand = Math.random();
    if (dayOfWeek >= 1 && dayOfWeek <= 4) {
      if (rand > 0.25) count = Math.floor(Math.random() * 6) + 1;
      if (rand > 0.8) count = Math.floor(Math.random() * 5) + 6;
    } else if (dayOfWeek === 5) {
      if (rand > 0.4) count = Math.floor(Math.random() * 4) + 1;
    } else {
      if (rand > 0.75) count = Math.floor(Math.random() * 3) + 1;
    }

    data.push({
      date: d.toISOString().split("T")[0],
      count,
      level: count === 0 ? 0 : count <= 2 ? 1 : count <= 4 ? 2 : count <= 7 ? 3 : 4,
    });
  }
  return data;
}
